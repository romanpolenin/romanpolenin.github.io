function updateCounter() {

    const project =
        projects[currentProject];

    const current =
        String(
            currentSlide + 1
        ).padStart(2, "0");

    const total =
        String(
            project.photos.length
        ).padStart(2, "0");

    counter.textContent =
        current +
        " / " +
        total;

}


