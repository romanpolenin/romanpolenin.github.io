/* =========================
   CREATE SLIDES
   ========================= */

function createSlides(project) {

    slidesContainer.innerHTML = "";

    project.photos.forEach(
        (photo, index) => {

            const slide =
                document.createElement(
                    "div"
                );

            slide.className =
                "slide";

            if (index === 0) {

                slide.classList.add(
                    "active"
                );

            }

            const image =
                document.createElement(
                    "img"
                );

            image.alt =
                project.name +
                " — photograph " +
                (index + 1);

            image.draggable =
                false;

            /*
             * Only the first image
             * is loaded immediately.
             */

            if (index === 0) {

                image.src =
                    photo;

            }

            /*
             * Store the real path
             * for later loading.
             */

            image.dataset.src =
                photo;

            slide.appendChild(
                image
            );

            slidesContainer.appendChild(
                slide
            );

        }
    );

}


/* =========================
   LOAD IMAGE
   ========================= */

function loadImage(index) {

    const slides =
        slidesContainer.querySelectorAll(
            ".slide"
        );

    const slide =
        slides[index];

    if (!slide) {
        return Promise.reject(
            new Error("Slide not found")
        );
    }

    const image =
        slide.querySelector("img");

    if (!image) {
        return Promise.reject(
            new Error("Image not found")
        );
    }

    const src =
        image.dataset.src;

    if (!src) {
        return Promise.reject(
            new Error("Image source not found")
        );
    }

    if (
        image.complete &&
        image.naturalWidth > 0
    ) {
        return Promise.resolve();
    }

    if (
        image.complete &&
        image.src &&
        image.naturalWidth === 0
    ) {
        return Promise.reject(
            new Error("Image failed to load")
        );
    }

    return new Promise(
        (resolve, reject) => {

            const handleLoad =
                () => {
                    cleanup();
                    resolve();
                };

            const handleError =
                () => {
                    cleanup();
                    reject(
                        new Error(
                            "Image failed to load"
                        )
                    );
                };

            const cleanup =
                () => {
                    image.removeEventListener(
                        "load",
                        handleLoad
                    );
                    image.removeEventListener(
                        "error",
                        handleError
                    );
                };

            image.addEventListener(
                "load",
                handleLoad
            );

            image.addEventListener(
                "error",
                handleError
            );

            if (!image.src) {
                image.src =
                    src;
            }

        }
    );

}


/* =========================
   PRELOAD ADJACENT IMAGES
   ========================= */

function preloadAdjacentImages() {

    const project =
        projects[currentProject];

    if (!project) {
        return;
    }

    const total =
        project.photos.length;

    const next =
        currentSlide + 1;

    if (next < total) {
        loadImage(next).catch(
            () => {}
        );
    }

    const previous =
        currentSlide - 1;

    if (previous >= 0) {
        loadImage(previous).catch(
            () => {}
        );
    }

}


/* =========================
   SHOW PROJECT
   ========================= */

async function showProject(
    projectId
) {

    const project =
        projects[projectId];

    if (!project) {
        return;
    }

    const loadToken =
        ++projectLoadToken;

    currentProject =
        projectId;

    currentSlide =
        0;

    isChanging =
        false;

    projectName.textContent =
        project.name;

    projectDescription.textContent =
        project.description;

    createSlides(
        project
    );

    updateCounter();

    projectButtons.forEach(
        button => {

            button.classList.remove(
                "active"
            );

            if (
                button.dataset.project
                === projectId
            ) {

                button.classList.add(
                    "active"
                );

            }

        }
    );

    about.classList.remove(
        "open"
    );

    try {

        await loadImage(0);

    }
    catch {

        if (
            loadToken ===
            projectLoadToken
        ) {
            console.warn(
                "First project image failed to load:",
                project.photos[0]
            );
        }

        return;

    }

    if (
        loadToken !==
        projectLoadToken
    ) {
        return;
    }

    preloadAdjacentImages();

}


/* =========================
   SHOW SLIDE
   ========================= */

async function showSlide(index) {

    if (isChanging) {
        return;
    }

    const slides =
        slidesContainer.querySelectorAll(
            ".slide"
        );

    if (!slides.length) {
        return;
    }

    const direction =
        index >= currentSlide
            ? 1
            : -1;

    let newIndex =
        index;

    if (newIndex < 0) {
        newIndex =
            slides.length - 1;
    }

    if (newIndex >= slides.length) {
        newIndex =
            0;
    }

    if (
        newIndex === currentSlide
    ) {
        return;
    }

    isChanging =
        true;

    const startIndex =
        newIndex;

    let loaded =
        false;

    while (!loaded) {

        try {

            await loadImage(
                newIndex
            );

            loaded =
                true;

        }
        catch {

            newIndex +=
                direction;

            if (newIndex < 0) {
                newIndex =
                    slides.length - 1;
            }

            if (
                newIndex >=
                slides.length
            ) {
                newIndex =
                    0;
            }

            if (
                newIndex ===
                    currentSlide ||
                newIndex ===
                    startIndex
            ) {

                isChanging =
                    false;

                return;

            }

        }

    }

    slides[currentSlide]
        .classList.remove(
            "active"
        );

    currentSlide =
        newIndex;

    slides[currentSlide]
        .classList.add(
            "active"
        );

    updateCounter();

    preloadAdjacentImages();

    setTimeout(
        () => {

            isChanging =
                false;

        },
        400
    );

}


/* =========================
   NEXT
   ========================= */

function nextSlide() {

    showSlide(
        currentSlide + 1
    );

}


/* =========================
   PREVIOUS
   ========================= */

function previousSlide() {

    showSlide(
        currentSlide - 1
    );

}


