/* =========================
   STATE
   ========================= */

let currentProject =
    "guatemala-street";

let currentSlide =
    0;

let isChanging =
    false;


/* =========================
   CREATE SLIDES
   ========================= */

function createSlides(project) {

    slidesContainer.innerHTML = "";

    project.photos.forEach(
        (photo, index) => {

            const slide =
                document.createElement(
                    "div"
                );

            slide.className =
                "slide";

            if (index === 0) {

                slide.classList.add(
                    "active"
                );

            }

            const image =
                document.createElement(
                    "img"
                );

            image.alt =
                project.name +
                " — photograph " +
                (index + 1);

            image.draggable =
                false;

            /*
             * Only the first image
             * is loaded immediately.
             */

            if (index === 0) {

                image.src =
                    photo;

            }

            /*
             * Store the real path
             * for later loading.
             */

            image.dataset.src =
                photo;

            slide.appendChild(
                image
            );

            slidesContainer.appendChild(
                slide
            );

        }
    );

}


/* =========================
   LOAD IMAGE
   ========================= */

function loadImage(index) {

    const slides =
        slidesContainer.querySelectorAll(
            ".slide"
        );

    const slide =
        slides[index];

    if (!slide) {
        return Promise.resolve();
    }

    const image =
        slide.querySelector("img");

    if (!image) {
        return Promise.resolve();
    }

    /*
     * Already loaded.
     */

    if (image.src) {

        return Promise.resolve();

    }

    const src =
        image.dataset.src;

    if (!src) {

        return Promise.resolve();

    }

    return new Promise(
        (resolve, reject) => {

            image.onload =
                () => resolve();

            image.onerror =
                () => reject();

            image.src =
                src;

        }
    );

}


/* =========================
   PRELOAD NEARBY IMAGE
   ========================= */

function preloadNearbyImages() {

    const project =
        projects[currentProject];

    if (!project) {
        return;
    }

    const total =
        project.photos.length;


    /*
     * Preload next image.
     */

    let next =
        currentSlide + 1;

    if (next >= total) {
        next = 0;
    }

    loadImage(next).catch(
        () => {}
    );


    /*
     * Preload previous image.
     */

    let previous =
        currentSlide - 1;

    if (previous < 0) {
        previous = total - 1;
    }

    loadImage(previous).catch(
        () => {}
    );

}


/* =========================
   SHOW PROJECT
   ========================= */

async function showProject(
    projectId
) {

    const project =
        projects[projectId];

    if (!project) {
        return;
    }


    currentProject =
        projectId;

    currentSlide =
        0;


    /* Project information */

    projectName.textContent =
        project.name;

    projectDescription.textContent =
        project.description;


    /* Create empty slides */

    createSlides(
        project
    );


    /* Load first image */

    try {

        await loadImage(0);

    }
    catch {

        return;

    }


    updateCounter();


    /* Active project */

    projectButtons.forEach(
        button => {

            button.classList.remove(
                "active"
            );

            if (
                button.dataset.project
                === projectId
            ) {

                button.classList.add(
                    "active"
                );

            }

        }
    );


    /* Close About */

    about.classList.remove(
        "open"
    );


    /*
     * Load next and previous
     * images in background.
     */

    preloadNearbyImages();

}


/* =========================
   SHOW SLIDE
   ========================= */

async function showSlide(index) {

    if (isChanging) {
        return;
    }


    const slides =
        slidesContainer.querySelectorAll(
            ".slide"
        );


    if (!slides.length) {
        return;
    }


    let newIndex =
        index;


    /* Loop */

    if (newIndex < 0) {

        newIndex =
            slides.length - 1;

    }


    if (
        newIndex >= slides.length
    ) {

        newIndex =
            0;

    }


    if (
        newIndex === currentSlide
    ) {

        return;

    }


    isChanging =
        true;


    try {

        /*
         * Load requested image
         * before displaying it.
         */

        await loadImage(
            newIndex
        );

    }
    catch {

        isChanging =
            false;

        return;

    }


    slides[currentSlide]
        .classList.remove(
            "active"
        );


    currentSlide =
        newIndex;


    slides[currentSlide]
        .classList.add(
            "active"
        );


    updateCounter();


    /*
     * Preload next/previous
     * images after changing.
     */

    preloadNearbyImages();


    setTimeout(
        () => {

            isChanging =
                false;

        },
        400
    );

}


/* =========================
   NEXT
   ========================= */

function nextSlide() {

    showSlide(
        currentSlide + 1
    );

}


/* =========================
   PREVIOUS
   ========================= */

function previousSlide() {

    showSlide(
        currentSlide - 1
    );

}


/* =========================
   COUNTER
   ========================= */

function updateCounter() {

    const project =
        projects[currentProject];

    const current =
        String(
            currentSlide + 1
        ).padStart(2, "0");

    const total =
        String(
            project.photos.length
        ).padStart(2, "0");

    counter.textContent =
        current +
        " / " +
        total;

}


