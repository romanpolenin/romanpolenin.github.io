/* =========================
   KEYBOARD
   ========================= */

document.addEventListener(
    "keydown",
    event => {

        if (
            about.classList.contains(
                "open"
            )
        ) {

            return;

        }


        if (
            event.key === "ArrowRight"
        ) {

            nextSlide();

        }


        if (
            event.key === "ArrowLeft"
        ) {

            previousSlide();

        }

    }
);


/* =========================
   TOUCH / SWIPE
   ========================= */

let touchStartX =
    0;

let touchStartY =
    0;

let touchEndX =
    0;

let touchEndY =
    0;


slidesContainer.addEventListener(
    "touchstart",
    event => {

        const touch =
            event.changedTouches[0];

        touchStartX =
            touch.screenX;

        touchStartY =
            touch.screenY;

    },
    { passive: true }
);


slidesContainer.addEventListener(
    "touchend",
    event => {

        const touch =
            event.changedTouches[0];

        touchEndX =
            touch.screenX;

        touchEndY =
            touch.screenY;

        const distanceX =
            touchEndX -
            touchStartX;

        const distanceY =
            touchEndY -
            touchStartY;

        if (
            Math.abs(distanceX) < 50 ||
            Math.abs(distanceX) <=
                Math.abs(distanceY)
        ) {
            return;
        }

        if (distanceX < 0) {
            nextSlide();
        }
        else {
            previousSlide();
        }

    },
    { passive: true }
);


